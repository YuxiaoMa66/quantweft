import numpy as np


def _real_float_array(values: np.ndarray) -> np.ndarray:
    """Convert before differences/products so integer arithmetic cannot wrap."""
    if values.dtype.kind not in "iuf":
        raise TypeError("arrays must have a real integer or floating dtype; complex/object/bool are unsupported")
    return values.astype(np.float64, copy=False)


def brownian_increments(
    paths: int,
    steps: int,
    T: float,
    seed: int | None = None,
) -> np.ndarray:
    """Generate independent Gaussian increments for standard Brownian motion.

    Parameters
    ----------
    paths : int
        Number of simulated sample paths. Must be a positive integer.
    steps : int
        Number of time discretization intervals. Must be a positive integer.
    T : float
        Total time horizon in years. Must be strictly positive and finite.
    seed : int | None, optional
        Non-negative integer (excluding bool) or None, for reproducible simulations.

    Returns
    -------
    np.ndarray
        2D array of shape (paths, steps) containing increments dW_k = W_{t_{k+1}} - W_{t_k}.
        Each increment is normally distributed with mean 0 and variance dt = T / steps.

    Raises
    ------
    TypeError
        If paths or steps is not an integer.
    ValueError
        If paths <= 0, steps <= 0, T <= 0, or T is not finite.
    """
    if isinstance(paths, (bool, np.bool_)) or not isinstance(paths, (int, np.integer)):
        raise TypeError(f"paths must be an integer, got {type(paths).__name__}")
    if isinstance(steps, (bool, np.bool_)) or not isinstance(steps, (int, np.integer)):
        raise TypeError(f"steps must be an integer, got {type(steps).__name__}")
    if paths <= 0:
        raise ValueError(f"paths must be strictly positive, got {paths}")
    if steps <= 0:
        raise ValueError(f"steps must be strictly positive, got {steps}")
    if isinstance(T, (bool, np.bool_)) or not isinstance(T, (int, float, np.integer, np.floating)):
        raise TypeError(f"T must be numeric, got {type(T).__name__}")
    if not math.isfinite(T) or T <= 0.0:
        raise ValueError(f"T must be strictly positive and finite, got {T}")
    if seed is not None:
        if isinstance(seed, (bool, np.bool_)) or not isinstance(seed, (int, np.integer)):
            raise TypeError("seed must be a non-negative integer or None, excluding bool")
        if seed < 0:
            raise ValueError("seed must be non-negative")

    dt = T / steps
    rng = np.random.default_rng(seed)
    std_dev = math.sqrt(dt)
    return rng.normal(loc=0.0, scale=std_dev, size=(paths, steps))


@np.errstate(over="raise", invalid="raise", divide="raise")
def ito_left(W: np.ndarray, integrand: np.ndarray) -> np.ndarray:
    r"""Compute the discrete left-point Itô stochastic integral.

    For a partition 0 = t_0 < t_1 < ... < t_N = T, computes:
        I_T = \sum_{k=0}^{N-1} H_{t_k} (W_{t_{k+1}} - W_{t_k})

    MATHEMATICAL ADAPTATION NOTICE:
    -------------------------------
    This function accepts numerical arrays and validates only their dimensions,
    shapes, non-emptiness, real numeric dtype, and absence of NaNs/infs.
    Integer/real arrays are converted to float64 before subtraction/products;
    complex, object and boolean arrays are rejected, not silently coerced.
    A discrete numerical array cannot mathematically verify whether `integrand`
    is adapted to the filtration generated by Brownian motion (F_t).
    The caller is mathematically responsible for ensuring that `integrand[:, k]`
    depends strictly on the history up to time t_k, and does NOT look ahead to
    future Brownian increments (W_{t_j} - W_{t_k} for j > k). Anticipating
    integrands violate the Itô isometry, destroy the martingale property, and
    render the integral non-Itô.

    Parameters
    ----------
    W : np.ndarray
        Brownian motion paths of shape (paths, steps + 1). Column 0 represents W_0.
    integrand : np.ndarray
        Evaluated integrand values at the left endpoint of each interval,
        shape (paths, steps). Column k represents H_{t_k}.

    Returns
    -------
    np.ndarray
        1D array of shape (paths,) containing the terminal value of the Itô integral
        for each path.

    Raises
    ------
    TypeError
        If W or integrand is not a numpy array.
    ValueError
        If arrays are empty, not 2D, have incompatible dimensions, or contain NaN/inf.
    """
    if not isinstance(W, np.ndarray):
        raise TypeError(f"W must be a numpy.ndarray, got {type(W).__name__}")
    if not isinstance(integrand, np.ndarray):
        raise TypeError(f"integrand must be a numpy.ndarray, got {type(integrand).__name__}")

    if W.ndim != 2:
        raise ValueError(f"W must be 2-dimensional (paths, steps + 1), got shape {W.shape}")
    if integrand.ndim != 2:
        raise ValueError(f"integrand must be 2-dimensional (paths, steps), got shape {integrand.shape}")

    paths, cols = W.shape
    if paths == 0 or cols <= 1:
        raise ValueError(f"W must have at least 1 path and 2 time columns, got shape {W.shape}")

    if integrand.shape[0] != paths:
        raise ValueError(
            f"Path count mismatch: W has {paths} paths, integrand has {integrand.shape[0]} paths"
        )
    if integrand.shape[1] != cols - 1:
        raise ValueError(
            f"Step count mismatch: W has {cols - 1} steps, integrand has {integrand.shape[1]} steps"
        )

    W = _real_float_array(W)
    integrand = _real_float_array(integrand)
    if not np.all(np.isfinite(W)):
        raise ValueError("W contains non-finite values (NaN or inf)")
    if not np.all(np.isfinite(integrand)):
        raise ValueError("integrand contains non-finite values (NaN or inf)")

    # Vectorized computation of discrete increments dW
    dW = W[:, 1:] - W[:, :-1]
    # Sum over time steps for each path
    return np.sum(integrand * dW, axis=1)


@np.errstate(over="raise", invalid="raise", divide="raise")
def quadratic_variation(W: np.ndarray) -> np.ndarray:
    r"""Compute pathwise realized quadratic variation [W, W]_T on a partition.

    Given Brownian motion paths W on partition 0 = t_0 < t_1 < ... < t_N = T:
        QV = \sum_{k=0}^{N-1} (W_{t_{k+1}} - W_{t_k})^2

    Real integer/floating arrays use float64 arithmetic before differencing.
    Complex/object/bool arrays are rejected; integer precision above 2**53
    is limited by float64 representation.

    Parameters
    ----------
    W : np.ndarray
        Brownian motion paths of shape (paths, steps + 1).

    Returns
    -------
    np.ndarray
        1D array of shape (paths,) containing the quadratic variation for each path.

    Raises
    ------
    TypeError
        If W is not a numpy.ndarray.
    ValueError
        If W is empty, not 2D, has fewer than 2 columns, or contains NaN/inf.
    """
    if not isinstance(W, np.ndarray):
        raise TypeError(f"W must be a numpy.ndarray, got {type(W).__name__}")
    if W.ndim != 2:
        raise ValueError(f"W must be 2-dimensional (paths, steps + 1), got shape {W.shape}")
    if W.shape[0] == 0 or W.shape[1] <= 1:
        raise ValueError(f"W must have at least 1 path and 2 time columns, got shape {W.shape}")
    W = _real_float_array(W)
    if not np.all(np.isfinite(W)):
        raise ValueError("W contains non-finite values (NaN or inf)")

    dW = W[:, 1:] - W[:, :-1]
    return np.sum(dW * dW, axis=1)


def gbm_exact(
    S0: float,
    drift: float,
    sigma: float,
    dt: float,
    dW: np.ndarray,
) -> np.ndarray:
    """Generate exact discrete sample paths of Geometric Brownian Motion (GBM).

    Model SDE:
        dS_t = drift * S_t * dt + sigma * S_t * dW_t

    Explicit analytic solution:
        S_{t_k} = S_0 * exp((drift - 0.5 * sigma^2) * t_k + sigma * W_{t_k})

    Parameters
    ----------
    S0 : float
        Initial asset price at t = 0. Must be strictly positive and finite.
    drift : float
        Stock price drift (mu_stock). In physical measure P with continuous dividend
        yield q and total drift mu_total, drift = mu_total - q.
        In risk-neutral measure Q, drift = r - q. Must be finite.
    sigma : float
        Volatility parameter. Must be non-negative and finite.
    dt : float
        Uniform time step size in years. Must be strictly positive and finite.
    dW : np.ndarray
        Brownian increments array of shape (paths, steps). Must be finite.

    Returns
    -------
    np.ndarray
        2D array of shape (paths, steps + 1) containing asset prices, with S[:, 0] = S0.

    Raises
    ------
    TypeError
        If S0, drift, sigma, or dt is not numeric, or dW is not a numpy array.
    ValueError
        If S0 <= 0, sigma < 0, dt <= 0, dW is not 2D, or inputs contain NaN/inf.
    """
    _validate_gbm_inputs(S0, drift, sigma, dt, dW)

    paths, steps = dW.shape
    # Cumulative Brownian motion paths: shape (paths, steps + 1)
    W = np.zeros((paths, steps + 1), dtype=float)
    np.cumsum(dW, axis=1, out=W[:, 1:])

    # Time grid t_k = k * dt
    t_grid = np.arange(steps + 1, dtype=float) * dt  # shape (steps + 1,)

    # Exact log-normal formula
    drift_term = (drift - 0.5 * sigma * sigma) * t_grid
    exponent = drift_term + sigma * W
    with np.errstate(over="raise", invalid="raise"):
        result = S0 * np.exp(exponent)
    if not np.all(np.isfinite(result)) or np.any(result <= 0):
        raise ValueError("GBM exact prices exceed floating-point range")
    return result


@np.errstate(over="raise", invalid="raise", divide="raise")
def gbm_euler(
    S0: float,
    drift: float,
    sigma: float,
    dt: float,
    dW: np.ndarray,
) -> np.ndarray:
    """Simulate Geometric Brownian Motion paths using Euler-Maruyama discretization.

    Discretization recursion:
        S_{t_{k+1}} = S_{t_k} + drift * S_{t_k} * dt + sigma * S_{t_k} * dW_k
                    = S_{t_k} * (1 + drift * dt + sigma * dW_k)

    Parameters
    ----------
    S0 : float
        Initial asset price at t = 0. Must be strictly positive and finite.
    drift : float
        Stock price drift (mu_stock). Must be finite.
    sigma : float
        Volatility parameter. Must be non-negative and finite.
    dt : float
        Uniform time step size in years. Must be strictly positive and finite.
    dW : np.ndarray
        Brownian increments array of shape (paths, steps).

    Returns
    -------
    np.ndarray
        2D array of shape (paths, steps + 1) containing discrete asset prices.

    Raises
    ------
    TypeError
        If inputs have invalid types.
    ValueError
        If parameters violate boundary conditions or arrays contain NaN/inf.
    """
    _validate_gbm_inputs(S0, drift, sigma, dt, dW)

    paths, steps = dW.shape
    S = np.zeros((paths, steps + 1), dtype=float)
    S[:, 0] = S0

    for k in range(steps):
        # Euler step using broadcasted array arithmetic
        S[:, k + 1] = S[:, k] * (1.0 + drift * dt + sigma * dW[:, k])

    return S


def _validate_gbm_inputs(
    S0: float,
    drift: float,
    sigma: float,
    dt: float,
    dW: np.ndarray,
) -> None:
    """Internal helper to validate GBM parameters and increments."""
    if not isinstance(S0, (int, float, np.floating)):
        raise TypeError(f"S0 must be numeric, got {type(S0).__name__}")
    if not math.isfinite(S0) or S0 <= 0.0:
        raise ValueError(f"S0 must be strictly positive and finite, got {S0}")

    if not isinstance(drift, (int, float, np.floating)):
        raise TypeError(f"drift must be numeric, got {type(drift).__name__}")
    if not math.isfinite(drift):
        raise ValueError(f"drift must be finite, got {drift}")

    if not isinstance(sigma, (int, float, np.floating)):
        raise TypeError(f"sigma must be numeric, got {type(sigma).__name__}")
    if not math.isfinite(sigma) or sigma < 0.0:
        raise ValueError(f"sigma must be non-negative and finite, got {sigma}")

    if not isinstance(dt, (int, float, np.floating)):
        raise TypeError(f"dt must be numeric, got {type(dt).__name__}")
    if not math.isfinite(dt) or dt <= 0.0:
        raise ValueError(f"dt must be strictly positive and finite, got {dt}")

    if not isinstance(dW, np.ndarray):
        raise TypeError(f"dW must be a numpy.ndarray, got {type(dW).__name__}")
    if dW.ndim != 2:
        raise ValueError(f"dW must be 2-dimensional (paths, steps), got shape {dW.shape}")
    if dW.shape[0] == 0 or dW.shape[1] == 0:
        raise ValueError(f"dW cannot be empty, got shape {dW.shape}")
    if not np.all(np.isfinite(dW)):
        raise ValueError("dW contains non-finite values (NaN or inf)")


@np.errstate(over="raise", invalid="raise", divide="raise")
def strong_error_rmse(exact_terminal: np.ndarray, approx_terminal: np.ndarray) -> float:
    r"""Compute pathwise strong root-mean-square error (RMSE) under common noise.

    RMSE = sqrt( (1 / M) * \sum_{m=1}^M (S_T^{approx, m} - S_T^{exact, m})^2 )

    Parameters
    ----------
    exact_terminal : np.ndarray
        Terminal asset values from exact simulation, shape (paths,).
    approx_terminal : np.ndarray
        Terminal asset values from approximation simulation, shape (paths,).

    Returns
    -------
    float
        The estimated strong RMSE.
    """
    if not isinstance(exact_terminal, np.ndarray) or not isinstance(approx_terminal, np.ndarray):
        raise TypeError("terminal values must be arrays")
    if exact_terminal.ndim != 1 or approx_terminal.shape != exact_terminal.shape or exact_terminal.size < 2:
        raise ValueError("terminal arrays must match and contain at least two paths")
    if not np.all(np.isfinite(exact_terminal)) or not np.all(np.isfinite(approx_terminal)):
        raise ValueError("terminal arrays must be finite")
    diff = approx_terminal - exact_terminal
    return float(np.sqrt(np.mean(diff ** 2)))


@np.errstate(over="raise", invalid="raise", divide="raise")
def weak_error_mean(
    exact_terminal: np.ndarray,
    approx_terminal: np.ndarray,
) -> Tuple[float, float]:
    r"""Compute weak error (bias in terminal expectation) and paired standard error.

    Weak error:
        Bias = | (1 / M) * \sum S_T^{approx, m} - (1 / M) * \sum S_T^{exact, m} |
    Paired standard error of the mean difference D_m = S_T^{approx, m} - S_T^{exact, m}:
        SE = std(D) / sqrt(M)

    Parameters
    ----------
    exact_terminal : np.ndarray
        Terminal asset values from exact simulation, shape (paths,).
    approx_terminal : np.ndarray
        Terminal asset values from approximation simulation, shape (paths,).

    Returns
    -------
    Tuple[float, float]
        (bias, paired_se)
    """
    if not isinstance(exact_terminal, np.ndarray) or not isinstance(approx_terminal, np.ndarray):
        raise TypeError("terminal values must be arrays")
    if exact_terminal.ndim != 1 or approx_terminal.shape != exact_terminal.shape or exact_terminal.size < 2:
        raise ValueError("terminal arrays must match and contain at least two paths")
    if not np.all(np.isfinite(exact_terminal)) or not np.all(np.isfinite(approx_terminal)):
        raise ValueError("terminal arrays must be finite")
    diff = approx_terminal - exact_terminal
    bias = float(np.abs(np.mean(diff)))
    paired_se = float(np.std(diff, ddof=1) / math.sqrt(len(diff)))
    return bias, paired_se


@np.errstate(over="raise", invalid="raise", divide="raise")
def radon_nikodym_density(
    W_P_terminal: np.ndarray,
    T: float,
    market_price_of_risk: float,
) -> np.ndarray:
    """Calculate the terminal Radon-Nikodym derivative Z_T = dQ / dP.

    Under constant market price of risk lambda = (mu - r) / sigma:
        Z_T = exp( -lambda * W_P(T) - 0.5 * lambda^2 * T )

    Parameters
    ----------
    W_P_terminal : np.ndarray
        Terminal Brownian motion values under physical measure P, shape (paths,).
    T : float
        Time horizon.
    market_price_of_risk : float
        The Sharpe ratio / market price of risk lambda.

    Returns
    -------
    np.ndarray
        Array of density values Z_T, shape (paths,).
    """
    if not isinstance(W_P_terminal, np.ndarray) or W_P_terminal.ndim != 1 or W_P_terminal.size == 0:
        raise ValueError("terminal Brownian array must be nonempty and one-dimensional")
    if not np.all(np.isfinite(W_P_terminal)) or not math.isfinite(T) or T < 0 or not math.isfinite(market_price_of_risk):
        raise ValueError("density inputs must be finite and T nonnegative")
    lam = market_price_of_risk
    result = np.exp(-lam * W_P_terminal - 0.5 * (lam ** 2) * T)
    if not np.all(np.isfinite(result)) or np.any(result <= 0):
        raise ValueError("density exceeds floating-point range")
    return result
